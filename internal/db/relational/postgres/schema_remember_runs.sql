
CREATE TABLE IF NOT EXISTS gb_remember_runs (
	id          BIGSERIAL PRIMARY KEY,
	user_id     TEXT NOT NULL,
	dataset     TEXT NOT NULL,
	kind        TEXT NOT NULL,
	params      JSONB NOT NULL DEFAULT '{}',
	artifact_id BIGINT,
	status      TEXT NOT NULL CHECK (status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	error       TEXT,
	started_at  TIMESTAMPTZ NOT NULL,
	finished_at TIMESTAMPTZ,
	classify_complexity_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (classify_complexity_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	classify_complexity_error       TEXT,
	classify_complexity_started_at  TIMESTAMPTZ,
	classify_complexity_finished_at TIMESTAMPTZ,
	classify_complexity_inference_ids  JSONB NOT NULL DEFAULT '[]',
	chunk_text_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (chunk_text_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	chunk_text_error       TEXT,
	chunk_text_started_at  TIMESTAMPTZ,
	chunk_text_finished_at TIMESTAMPTZ,
	extract_graph_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (extract_graph_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	extract_graph_error       TEXT,
	extract_graph_started_at  TIMESTAMPTZ,
	extract_graph_finished_at TIMESTAMPTZ,
	extract_graph_inference_ids  JSONB NOT NULL DEFAULT '[]',
	summarize_chunk_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (summarize_chunk_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	summarize_chunk_error       TEXT,
	summarize_chunk_started_at  TIMESTAMPTZ,
	summarize_chunk_finished_at TIMESTAMPTZ,
	summarize_chunk_inference_ids  JSONB NOT NULL DEFAULT '[]',
	load_candidates_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (load_candidates_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	load_candidates_error       TEXT,
	load_candidates_started_at  TIMESTAMPTZ,
	load_candidates_finished_at TIMESTAMPTZ,
	load_candidates_inference_ids  JSONB NOT NULL DEFAULT '[]',
	resolve_edges_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (resolve_edges_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	resolve_edges_error       TEXT,
	resolve_edges_started_at  TIMESTAMPTZ,
	resolve_edges_finished_at TIMESTAMPTZ,
	resolve_edges_inference_ids  JSONB NOT NULL DEFAULT '[]',
	store_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (store_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	store_error       TEXT,
	store_started_at  TIMESTAMPTZ,
	store_finished_at TIMESTAMPTZ,
	store_inference_ids  JSONB NOT NULL DEFAULT '[]',
	store_series_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (store_series_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	store_series_error       TEXT,
	store_series_started_at  TIMESTAMPTZ,
	store_series_finished_at TIMESTAMPTZ,
	classify_graph_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (classify_graph_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	classify_graph_error       TEXT,
	classify_graph_started_at  TIMESTAMPTZ,
	classify_graph_finished_at TIMESTAMPTZ,
	classify_graph_inference_ids  JSONB NOT NULL DEFAULT '[]',
	resolve_geo_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (resolve_geo_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	resolve_geo_error       TEXT,
	resolve_geo_started_at  TIMESTAMPTZ,
	resolve_geo_finished_at TIMESTAMPTZ,
	resolve_geo_inference_ids  JSONB NOT NULL DEFAULT '[]',
	web_search_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (web_search_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	web_search_error       TEXT,
	web_search_started_at  TIMESTAMPTZ,
	web_search_finished_at TIMESTAMPTZ,
	web_search_inference_ids  JSONB NOT NULL DEFAULT '[]',
	fetch_series_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (fetch_series_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	fetch_series_error       TEXT,
	fetch_series_started_at  TIMESTAMPTZ,
	fetch_series_finished_at TIMESTAMPTZ,
	fetch_series_inference_ids  JSONB NOT NULL DEFAULT '[]',
	observe_series_status      TEXT NOT NULL DEFAULT 'not_started' CHECK (observe_series_status IN ('not_started', 'started', 'succeeded', 'failed', 'skipped')),
	observe_series_error       TEXT,
	observe_series_started_at  TIMESTAMPTZ,
	observe_series_finished_at TIMESTAMPTZ,
	observe_series_inference_ids  JSONB NOT NULL DEFAULT '[]'
);
CREATE INDEX IF NOT EXISTS idx_gb_remember_runs_dataset ON gb_remember_runs(user_id, dataset);
CREATE INDEX IF NOT EXISTS idx_gb_remember_runs_status ON gb_remember_runs(status);

CREATE TABLE IF NOT EXISTS gb_remember_run_stage_outputs (
	id         BIGSERIAL PRIMARY KEY,
	run_id     BIGINT NOT NULL REFERENCES gb_remember_runs(id) ON DELETE CASCADE,
	stage      TEXT NOT NULL CHECK (stage IN ('classify_complexity', 'chunk_text', 'extract_graph', 'summarize_chunk', 'load_candidates', 'resolve_edges', 'store', 'store_series', 'classify_graph', 'resolve_geo', 'web_search', 'fetch_series', 'observe_series')),
	name       TEXT NOT NULL,
	label      TEXT NOT NULL DEFAULT '',
	output     JSONB NOT NULL,
	created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_gb_remember_run_stage_outputs_run ON gb_remember_run_stage_outputs(run_id, stage);
CREATE INDEX IF NOT EXISTS idx_gb_remember_run_stage_outputs_created ON gb_remember_run_stage_outputs(created_at);
